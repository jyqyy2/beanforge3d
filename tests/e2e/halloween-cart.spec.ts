import { test, expect } from '@playwright/test'

test('Halloween design persists as a distinct, unpriced cart item', async ({ page }) => {
  await page.goto('/studio/halloween')
  await page.getByRole('button', { name: 'Start new design' }).click()
  const confirm = page.getByRole('group', { name: 'Start a new Halloween design' })
  await confirm.getByRole('button', { name: /start new/i }).click()

  const add = page.getByRole('button', { name: 'Add my creation to cart' })
  await expect(add).toBeDisabled()
  await page.locator('.halloween-keycap-card').first().click()
  await expect(add).toBeEnabled()
  await add.click()
  await page.getByRole('link', { name: 'View cart' }).click()
  await expect(page.getByRole('heading', { name: 'Halloween Fidget Clicker' })).toBeVisible()
  await expect(page.getByText('Layout: 1x1 · Keycaps: pumpkin')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Pay securely with Stripe' })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Halloween Fidget Clicker' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Pay securely with Stripe' })).toBeDisabled()
})

test('different layouts remain separate and incomplete boards cannot be added', async ({ page }) => {
  await page.goto('/studio/halloween')
  await page.getByRole('button', { name: /2 × 1/ }).click()
  const add = page.getByRole('button', { name: 'Add my creation to cart' })
  await page.locator('.halloween-keycap-card').first().click()
  await expect(add).toBeDisabled()
  await page.locator('.halloween-keycap-card').nth(1).click()
  await expect(add).toBeEnabled()
  await add.click()
  await page.getByRole('button', { name: /1 × 1/ }).click()
  await add.click()
  await page.goto('/cart')
  await expect(page.getByRole('article')).toHaveCount(2)
  await expect(page.getByRole('button', { name: 'Pay securely with Stripe' })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('article')).toHaveCount(2)
})

test('extra keycaps can be chosen, removed, and saved without changing the board', async ({ page }) => {
  await page.goto('/studio/halloween')
  await page.locator('.halloween-keycap-card').first().click()
  const extras = page.getByRole('region', { name: 'Additional keycaps' })
  await extras.getByRole('button', { name: '+ Add another keycap' }).click()
  const add = page.getByRole('button', { name: 'Add my creation to cart' })
  await expect(add).toBeDisabled()
  await extras.getByRole('group', { name: 'Choose extra keycap 1' }).getByRole('button', { name: 'Ghost' }).click()
  await expect(add).toBeEnabled()
  await page.reload()
  await expect(extras.getByRole('button', { name: 'Ghost' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.halloween-slot')).toHaveCount(1)
  await add.click()
  await page.goto('/cart')
  await expect(page.getByText('Extra keycaps: ghost')).toBeVisible()
  await page.goto('/studio/halloween')
  await extras.getByRole('button', { name: 'Remove keycap' }).click()
  await expect(extras.getByRole('group', { name: 'Choose extra keycap 1' })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
