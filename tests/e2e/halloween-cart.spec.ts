import { test, expect } from '@playwright/test'

test('Halloween design persists as a distinct, unpriced cart item', async ({ page }) => {
  await page.goto('/studio/halloween')
  await page.getByRole('button', { name: 'Start new design' }).click()
  const confirm = page.getByRole('group', { name: 'Start a new Halloween design' })
  await confirm.getByRole('button', { name: /start new/i }).click()

  const add = page.getByRole('button', { name: 'Add my creation to cart' })
  await expect(add).toBeDisabled()
  await page.locator('.halloween-keycap-card').first().click()
  await expect(add).toBeEnabled()
  await add.click()
  const popup = page.getByRole('dialog', { name: '✓ Item added to your cart' })
  await expect(popup).toBeVisible()
  await expect(popup.getByRole('button', { name: 'Checkout unavailable' })).toBeDisabled()
  await expect(page.getByText('Your design was added to the cart.')).toHaveCount(0)
  await popup.getByRole('link', { name: 'View cart (1)' }).click()
  await expect(page.getByRole('heading', { name: 'Halloween Fidget Clicker' })).toBeVisible()
  await expect(page.getByText('Layout: 1x1 · Keycaps: pumpkin')).toBeVisible()
  await expect(page.getByRole('img', { name: /1x1 Cream Halloween clicker with pumpkin keycaps/ })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Pay securely with Stripe' })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Halloween Fidget Clicker' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Pay securely with Stripe' })).toBeDisabled()
})

test('different layouts remain separate and incomplete boards cannot be added', async ({ page }) => {
  await page.goto('/studio/halloween')
  await page.getByRole('button', { name: /2 × 1/ }).click()
  const add = page.getByRole('button', { name: 'Add my creation to cart' })
  await page.locator('.halloween-keycap-card').first().click()
  await expect(add).toBeDisabled()
  await page.locator('.halloween-keycap-card').nth(1).click()
  await expect(add).toBeEnabled()
  await add.click()
  await page.getByRole('button', { name: /1 × 1/ }).click()
  await add.click()
  await page.goto('/cart')
  await expect(page.getByRole('article')).toHaveCount(2)
  await expect(page.getByRole('button', { name: 'Pay securely with Stripe' })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('article')).toHaveCount(2)
})

test('cart confirmation can be dismissed and reflects repeated additions', async ({ page }) => {
  await page.goto('/studio/halloween')
  await page.locator('.halloween-keycap-card').first().click()
  const add = page.getByRole('button', { name: 'Add my creation to cart' })
  await add.click()
  const popup = page.getByRole('dialog', { name: '✓ Item added to your cart' })
  await expect(popup.getByRole('link', { name: 'View cart (1)' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(popup).toHaveCount(0)
  await expect(add).toBeFocused()
  await add.click()
  await expect(popup.getByRole('link', { name: 'View cart (2)' })).toBeVisible()
  await popup.getByRole('button', { name: 'Continue shopping' }).click()
  await expect(popup).toHaveCount(0)
  await add.click()
  await popup.getByRole('button', { name: 'Close cart confirmation' }).click()
  await expect(popup).toHaveCount(0)
})

test('extra keycap quantities persist and transfer to cart without changing the board', async ({ page }) => {
  await page.goto('/studio/halloween')
  await page.locator('.halloween-keycap-card').first().click()
  const extras = page.getByRole('region', { name: 'Additional keycaps' })
  const ghost = extras.getByRole('group', { name: 'Ghost extra keycaps' })
  await expect(ghost.locator('output')).toHaveText('0')
  await ghost.getByRole('button', { name: 'Add one Ghost extra keycap' }).click({ clickCount: 2 })
  await expect(ghost.locator('output')).toHaveText('2')
  await ghost.getByRole('button', { name: 'Remove one Ghost extra keycap' }).click()
  await expect(ghost.locator('output')).toHaveText('1')
  await ghost.getByRole('button', { name: 'Add one Ghost extra keycap' }).click()
  await extras.getByRole('button', { name: 'Add one Cat back extra keycap' }).click()
  const add = page.getByRole('button', { name: 'Add my creation to cart' })
  await expect(add).toBeEnabled()
  await page.reload()
  await expect(ghost.locator('output')).toHaveText('2')
  await expect(page.locator('.halloween-slot')).toHaveCount(1)
  await add.click()
  await page.goto('/cart')
  await expect(page.getByText('Extra keycaps: ghost × 2 · cat-back × 1')).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('beanforge-cart') ?? '[]')[0].halloweenConfiguration.extras)).toEqual(['ghost', 'ghost', 'cat-back'])
  await expect(page.getByRole('img', { name: /Halloween clicker with pumpkin keycaps/ })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Pay securely with Stripe' })).toBeDisabled()
  await page.reload()
  await expect(page.getByText('Extra keycaps: ghost × 2 · cat-back × 1')).toBeVisible()
  await page.goto('/studio/halloween')
  await ghost.getByRole('button', { name: 'Remove one Ghost extra keycap' }).click()
  await expect(ghost.locator('output')).toHaveText('1')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

